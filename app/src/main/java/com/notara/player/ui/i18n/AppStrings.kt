enum class AppLanguage(val code: String, val nativeName: String) {
    INDONESIAN("id", "Bahasa Indonesia"),
    ENGLISH("en", "English"),
    KOREAN("ko", "한국어"),
    JAPANESE("ja", "日本語")
}

object LanguagePreferences {
    private const val PREFS = "notara_lang_prefs"
    private const val KEY = "selected_lang"

    fun load(context: Context): AppLanguage {
        val code = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
            .getString(KEY, AppLanguage.INDONESIAN.code)
        return AppLanguage.entries.firstOrNull { it.code == code } ?: AppLanguage.INDONESIAN
    }

    fun save(context: Context, lang: AppLanguage) {
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
            .edit()
            .putString(KEY, lang.code)
            .apply()
    }
}

